PRAGMA foreign_keys=ON; PRAGMA journal_mode=WAL;
 CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,shop TEXT NOT NULL,expires INTEGER NOT NULL);
 CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY,shop TEXT NOT NULL,kind TEXT NOT NULL,data TEXT NOT NULL,at TEXT NOT NULL,version INTEGER NOT NULL,UNIQUE(shop,version));
 CREATE TRIGGER IF NOT EXISTS immutable_update BEFORE UPDATE ON events BEGIN SELECT RAISE(ABORT,'immutable ledger'); END;
 CREATE TRIGGER IF NOT EXISTS immutable_delete BEFORE DELETE ON events BEGIN SELECT RAISE(ABORT,'immutable ledger'); END;
 CREATE TABLE IF NOT EXISTS scenarios(id TEXT PRIMARY KEY,token TEXT NOT NULL,data TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS operations(id TEXT PRIMARY KEY,token TEXT NOT NULL,shop TEXT NOT NULL,version INTEGER NOT NULL,kind TEXT NOT NULL,data TEXT NOT NULL,hash TEXT NOT NULL,expires INTEGER NOT NULL,result TEXT);
 
