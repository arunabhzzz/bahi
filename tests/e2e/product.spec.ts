import { test, expect } from "@playwright/test";
import { kg, say, yes } from "./helpers";

test("sale, correction, payment, analyst questions and a restock draft through real MCP", async ({ page, browser }) => {
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(error.message));
  await page.goto("/");
  await expect(page.getByText("Alexa+ simulation · real ledger · synthetic demo data")).toBeVisible();
  await expect(page.getByTestId("stock-Sugar")).toBeVisible();
  const start = await kg(page);
  await say(page, "Sold 2 kg cheeni to Ramesh, he paid 30");
  await expect(page.getByTestId("action-preview")).toContainText("Sale to Ramesh: 2 kg Sugar ₹96");
  await yes(page);
  expect(await kg(page)).toBe(start - 2);
  await say(page, "no, that was 1 kg");
  await expect(page.getByTestId("action-preview")).toContainText("Ramesh's credit goes down ₹48");
  await yes(page);
  expect(await kg(page)).toBe(start - 1);
  await say(page, "Ramesh paid 18");
  await yes(page);
  await say(page, "Why were sales down on Tuesday?");
  await expect(page.getByTestId("insight")).toContainText("didn't buy anything");
  await expect(page.locator(".chart")).toBeVisible();
  await page.screenshot({ path: "docs/evidence/analyst.png", fullPage: true });
  await say(page, "Who's a credit risk?");
  await expect(page.getByTestId("insight")).toContainText("Farooq");
  await say(page, "plan budget 2000 reserve 500 fee 0");
  await expect(page.getByTestId("restock-plan")).toContainText("₹500");
  await say(page, "leave out biscuits");
  await say(page, "budget 2500");
  await expect(page.getByTestId("plan-comparison")).toBeVisible();
  await say(page, "save draft");
  await yes(page);
  await page.reload();
  await expect(page.getByTestId("order-drafts")).toContainText("unsent");
  expect(await kg(page)).toBe(start - 1);
  const ctx = await browser.newContext();
  const other = await ctx.newPage();
  await other.goto("/");
  await expect(other.getByTestId("order-drafts")).toContainText("No unsent orders");
  await ctx.close();
  await page.screenshot({ path: "docs/evidence/desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "docs/evidence/mobile.png", fullPage: true });
  expect(pageErrors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
